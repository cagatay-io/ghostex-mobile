// Adds the app's WidgetKit extension to the generated iOS project: the Live Activity's presentations and the Home
// Screen widgets, in one extension so a build signed by a personal team spends one App ID on it. `ios/` is Expo
// prebuild output and never edited by hand, so this plugin is where the extension target lives:
//
// - the target `GhostexLiveActivityExtension` (an app extension, WidgetKit extension point), bundle id
//   `<app bundle id>.liveactivity`, the app's team and deployment target, Swift 5 language mode;
// - its sources, compiled in place (no copies): from `modules/ghostex-live-activity/ios` the attributes the app
//   module shares (`Shared/`), the Live Activity's SwiftUI views (`Extension/`) and the asset catalog; from
//   `modules/ghostex-widgets/ios` where the widget snapshot lives (`Shared/`) and the widgets (`Extension/`);
// - its Info.plist, written to `ios/GhostexLiveActivityExtension/Info.plist` with the app's version and build number,
//   because an extension must carry the same version as the app that contains it;
// - the App Group the app and the widgets share: the extension's entitlements file carries the group of app.json's
//   `ios.entitlements` (`com.apple.security.application-groups`), and both Info.plists name it (`GhostexAppGroup`)
//   through the build setting `GHOSTEX_APP_GROUP`, so a build signed by another team overrides one setting;
// - the app embeds the `.appex` (PlugIns) and depends on the target.
//
// The target, its bundle id and the app's embedding are created once. Its files and settings are set from this file
// on every prebuild, also when `expo prebuild` without `--clean` runs on a project an earlier prebuild wrote, so an
// existing target ends up as a new one.
//
// No push entitlement (`aps-environment`): the Live Activity's content comes through ActivityKit, the widgets'
// through the App Group. `NSSupportsLiveActivities` is set in app.json's `ios.infoPlist`.
// One plugin owns the target: Expo runs a later plugin's mods first, so a second plugin on this target would depend
// on the order of app.json's plugin list.
const { withDangerousMod, withInfoPlist, withXcodeProject } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

// Not `GhostexLiveActivity`: that is the Swift module of the app-side pod, and a target of the same name would
// put a second module of that name next to it in the build products.
const TARGET_NAME = 'GhostexLiveActivityExtension';
const BUNDLE_SUFFIX = 'liveactivity';
/** Relative to `ios/`, where the Xcode project sits. */
const SOURCE_ROOT = '../modules';
const SOURCE_FILES = [
  'ghostex-live-activity/ios/Shared/GhostexActivityAttributes.swift',
  'ghostex-live-activity/ios/Extension/GhostexLiveActivityWidget.swift',
  'ghostex-live-activity/ios/Extension/GhostexActivityViews.swift',
  'ghostex-live-activity/ios/Extension/GhostexAgentMarks.swift',
  'ghostex-widgets/ios/Shared/GhostexWidgetStore.swift',
  'ghostex-widgets/ios/Extension/GhostexWidgetSnapshot.swift',
  'ghostex-widgets/ios/Extension/GhostexStatusWidget.swift',
  'ghostex-widgets/ios/Extension/GhostexStatusViews.swift',
];
const RESOURCE_FILES = ['ghostex-live-activity/ios/Extension/Assets.xcassets'];
/** The target's build phases, all of them this plugin's: name, type and files. */
const BUILD_PHASES = [
  ['Sources', 'PBXSourcesBuildPhase', SOURCE_FILES],
  ['Resources', 'PBXResourcesBuildPhase', RESOURCE_FILES],
  ['Frameworks', 'PBXFrameworksBuildPhase', []],
];
const INFO_PLIST = `${TARGET_NAME}/Info.plist`;
const ENTITLEMENTS = `${TARGET_NAME}/${TARGET_NAME}.entitlements`;
const APP_GROUP_ENTITLEMENT = 'com.apple.security.application-groups';
/** The build setting both bundles read the group from; their Info.plists name it as `GhostexAppGroup`. */
const APP_GROUP_SETTING = 'GHOSTEX_APP_GROUP';

function xmlText(value) {
  return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function infoPlist({ version, buildNumber }) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by plugins/withWidgets.js; regenerated on every prebuild. -->
<plist version="1.0">
<dict>
  <key>CFBundleDevelopmentRegion</key>
  <string>$(DEVELOPMENT_LANGUAGE)</string>
  <key>CFBundleDisplayName</key>
  <string>Ghostex</string>
  <key>CFBundleExecutable</key>
  <string>$(EXECUTABLE_NAME)</string>
  <key>CFBundleIdentifier</key>
  <string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
  <key>CFBundleInfoDictionaryVersion</key>
  <string>6.0</string>
  <key>GhostexAppGroup</key>
  <string>$(${APP_GROUP_SETTING})</string>
  <key>CFBundleName</key>
  <string>$(PRODUCT_NAME)</string>
  <key>CFBundlePackageType</key>
  <string>$(PRODUCT_BUNDLE_PACKAGE_TYPE)</string>
  <key>CFBundleShortVersionString</key>
  <string>${xmlText(version)}</string>
  <key>CFBundleVersion</key>
  <string>${xmlText(buildNumber)}</string>
  <key>NSExtension</key>
  <dict>
    <key>NSExtensionPointIdentifier</key>
    <string>com.apple.widgetkit-extension</string>
  </dict>
</dict>
</plist>
`;
}

function entitlements() {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by plugins/withWidgets.js; regenerated on every prebuild. -->
<plist version="1.0">
<dict>
  <key>${APP_GROUP_ENTITLEMENT}</key>
  <array>
    <string>$(${APP_GROUP_SETTING})</string>
  </array>
</dict>
</plist>
`;
}

/** The App Group of app.json's `ios.entitlements`, which the app and the widgets share. */
function appGroupOf(cfg) {
  const groups = cfg.ios?.entitlements?.[APP_GROUP_ENTITLEMENT];
  const group = Array.isArray(groups) ? groups[0] : undefined;
  if (typeof group !== 'string' || group.length === 0) {
    throw new Error(`withWidgets: app.json ios.entitlements needs ${APP_GROUP_ENTITLEMENT} with the widgets' group`);
  }
  return group;
}

function withExtensionFiles(config) {
  return withDangerousMod(config, [
    'ios',
    (cfg) => {
      const version = cfg.version;
      const buildNumber = cfg.ios?.buildNumber;
      if (!version || !buildNumber) {
        throw new Error('withWidgets: the extension needs the app version and ios.buildNumber');
      }
      const write = (relative, text) => {
        const file = path.join(cfg.modRequest.platformProjectRoot, relative);
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, text);
      };
      write(INFO_PLIST, infoPlist({ version, buildNumber }));
      write(ENTITLEMENTS, entitlements());
      return cfg;
    },
  ]);
}

/** The app reads the group from its Info.plist, as the extension does. */
function withAppGroupInfoPlist(config) {
  return withInfoPlist(config, (cfg) => {
    cfg.modResults.GhostexAppGroup = `$(${APP_GROUP_SETTING})`;
    return cfg;
  });
}

/** Sets `key` in every build configuration of a target. */
function setTargetSetting(project, buildConfigurationList, key, value) {
  const configurations = project.pbxXCBuildConfigurationSection();
  for (const entry of project.pbxXCConfigurationList()[buildConfigurationList].buildConfigurations) {
    configurations[entry.value].buildSettings[key] = value;
  }
}

/** A build setting of the app target's Release configuration, or of the project, unquoted. */
function appBuildSetting(project, appTarget, key) {
  const configurations = project.pbxXCBuildConfigurationSection();
  const lists = project.pbxXCConfigurationList();
  const read = (listId) => {
    const list = lists[listId];
    const release = list?.buildConfigurations.find((entry) => entry.comment === 'Release');
    const value = release && configurations[release.value]?.buildSettings?.[key];
    return typeof value === 'string' ? value.replace(/^"(.*)"$/, '$1') : undefined;
  };
  const projectListId = project.getFirstProject().firstProject.buildConfigurationList;
  return read(appTarget.target.buildConfigurationList) ?? read(projectListId);
}

/** The uuid of the object named `name` in a section; the `xcode` package writes a new target's name quoted, Xcode not. */
function uuidNamed(section, name) {
  return Object.keys(section).find(
    (key) => !key.endsWith('_comment') && String(section[key].name).replace(/^"(.*)"$/, '$1') === name,
  );
}

function deleteObject(section, uuid) {
  delete section[uuid];
  delete section[`${uuid}_comment`];
}

/**
 * Takes out what an earlier prebuild gave the existing target: the group with its file references and the build phases
 * with their build files. Added again from the lists above, the target then has exactly the files a new one gets.
 */
function removeOwnedFiles(project, targetUuid) {
  const objects = project.hash.project.objects;
  const groupUuid = uuidNamed(objects.PBXGroup, TARGET_NAME);
  if (groupUuid) {
    for (const child of objects.PBXGroup[groupUuid].children) deleteObject(objects.PBXFileReference, child.value);
    const mainGroup = objects.PBXGroup[project.getFirstProject().firstProject.mainGroup];
    mainGroup.children = mainGroup.children.filter((child) => child.value !== groupUuid);
    deleteObject(objects.PBXGroup, groupUuid);
  }
  const target = objects.PBXNativeTarget[targetUuid];
  target.buildPhases = target.buildPhases.filter((phase) => {
    const type = BUILD_PHASES.find(([name]) => name === phase.comment)?.[1];
    if (!type) return true;
    for (const file of objects[type][phase.value].files) deleteObject(objects.PBXBuildFile, file.value);
    deleteObject(objects[type], phase.value);
    return false;
  });
}

/** Creates the target; the app embeds it and depends on it. */
function addExtensionTarget(project, cfg, appTarget) {
  const appBundleId = cfg.ios?.bundleIdentifier;
  if (!appBundleId) throw new Error('withWidgets: ios.bundleIdentifier is required');
  // addTarget embeds an app extension into the project's first target and makes that target depend on it;
  // the first target must be the app.
  if (project.getFirstTarget().uuid !== appTarget.uuid) {
    throw new Error('withWidgets: the application is not the first target of the Xcode project');
  }
  const objects = project.hash.project.objects;
  objects.PBXTargetDependency = objects.PBXTargetDependency ?? {};
  objects.PBXContainerItemProxy = objects.PBXContainerItemProxy ?? {};
  return project.addTarget(TARGET_NAME, 'app_extension', TARGET_NAME, `${appBundleId}.${BUNDLE_SUFFIX}`).uuid;
}

function withExtensionTarget(config) {
  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const appGroup = `"${appGroupOf(cfg)}"`;
    const appTarget = project.getTarget('com.apple.product-type.application');
    if (!appTarget) throw new Error('withWidgets: no application target in the Xcode project');
    setTargetSetting(project, appTarget.target.buildConfigurationList, APP_GROUP_SETTING, appGroup);

    const existingUuid = uuidNamed(project.pbxNativeTargetSection(), TARGET_NAME);
    if (existingUuid) removeOwnedFiles(project, existingUuid);
    const targetUuid = existingUuid ?? addExtensionTarget(project, cfg, appTarget);

    const group = project.addPbxGroup([...SOURCE_FILES, ...RESOURCE_FILES], TARGET_NAME, SOURCE_ROOT);
    project.addToPbxGroup(group.uuid, project.getFirstProject().firstProject.mainGroup);
    for (const [name, type, files] of BUILD_PHASES) project.addBuildPhase(files, type, name, targetUuid);

    const deploymentTarget = appBuildSetting(project, appTarget, 'IPHONEOS_DEPLOYMENT_TARGET');
    const teamId = cfg.ios?.appleTeamId;
    const configurations = project.pbxXCBuildConfigurationSection();
    const list = project.pbxXCConfigurationList()[project.pbxNativeTargetSection()[targetUuid].buildConfigurationList];
    for (const entry of list.buildConfigurations) {
      const settings = configurations[entry.value].buildSettings;
      Object.assign(settings, {
        INFOPLIST_FILE: `"${INFO_PLIST}"`,
        GENERATE_INFOPLIST_FILE: 'NO',
        CODE_SIGN_ENTITLEMENTS: `"${ENTITLEMENTS}"`,
        [APP_GROUP_SETTING]: appGroup,
        PRODUCT_NAME: `"${TARGET_NAME}"`,
        SWIFT_VERSION: '5.0',
        TARGETED_DEVICE_FAMILY: '"1,2"',
        SDKROOT: 'iphoneos',
        APPLICATION_EXTENSION_API_ONLY: 'YES',
        CLANG_ENABLE_MODULES: 'YES',
        CODE_SIGN_STYLE: 'Automatic',
        SKIP_INSTALL: 'YES',
        ASSETCATALOG_COMPILER_GENERATE_SWIFT_ASSET_SYMBOL_EXTENSIONS: 'NO',
      });
      if (deploymentTarget) settings.IPHONEOS_DEPLOYMENT_TARGET = deploymentTarget;
      else delete settings.IPHONEOS_DEPLOYMENT_TARGET;
      if (teamId) settings.DEVELOPMENT_TEAM = teamId;
      else delete settings.DEVELOPMENT_TEAM;
    }
    return cfg;
  });
}

module.exports = function withWidgets(config) {
  return withExtensionTarget(withAppGroupInfoPlist(withExtensionFiles(config)));
};
