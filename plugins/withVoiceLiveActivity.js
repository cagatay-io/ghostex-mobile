// The push-to-talk call's Live Activity on iOS: Talk / Send on the lock screen and in the Dynamic
// Island while a voice agent call is push-to-talk (modules/ghostex-native/ios/GhostexVoiceActivity.swift).
//
// At prebuild this adds a WidgetKit extension target, GhostexVoiceActivity, embedded in the app:
// its sources are plugins/voice-live-activity/ plus the native module's
// GhostexVoiceActivityAttributes.swift (ActivityKit matches an activity to its widget by that type,
// so both sides compile the same file). The Talk / Send intent is compiled into the app target too,
// so iOS runs it inside the app, where the call engine is. The app's Info.plist gets
// NSSupportsLiveActivities. The extension's version and build number are the app's (App Store
// Connect refuses an extension whose CFBundleVersion differs), and it is signed like the app
// (automatic signing; the TestFlight build passes DEVELOPMENT_TEAM and -allowProvisioningUpdates,
// which registers the extension's bundle id).
//
// CDXC:VoiceMode 2026-11-04 DECISION: User (Q2): "Add a Live Activity with Talk / Send for
// push-to-talk on the lock screen and Dynamic Island"; the coordinator asked for the widget extension
// "through an Expo config plugin, so prebuild makes the target".
const { IOSConfig, withDangerousMod, withInfoPlist, withXcodeProject } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const TARGET = 'GhostexVoiceActivity';
const WIDGET_SOURCES = [
  'GhostexVoiceActivityWidget.swift',
  'GhostexVoiceActivityAttributes.swift',
  'GhostexVoiceTalkIntent.swift',
];
/** The app target's copy of the intent; its own name keeps it apart from the extension's copy. */
const APP_INTENT_FILE = 'GhostexVoiceTalkIntentApp.swift';

const TEMPLATE_DIR = path.join(__dirname, 'voice-live-activity');
const ATTRIBUTES_SOURCE = path.join(
  __dirname,
  '..',
  'modules',
  'ghostex-native',
  'ios',
  'GhostexVoiceActivityAttributes.swift',
);

function widgetInfoPlist(version, buildNumber) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by plugins/withVoiceLiveActivity.js. -->
<plist version="1.0">
<dict>
  <key>CFBundleDevelopmentRegion</key><string>$(DEVELOPMENT_LANGUAGE)</string>
  <key>CFBundleDisplayName</key><string>Ghostex</string>
  <key>CFBundleExecutable</key><string>$(EXECUTABLE_NAME)</string>
  <key>CFBundleIdentifier</key><string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>CFBundleName</key><string>$(PRODUCT_NAME)</string>
  <key>CFBundlePackageType</key><string>$(PRODUCT_BUNDLE_PACKAGE_TYPE)</string>
  <key>CFBundleShortVersionString</key><string>${version}</string>
  <key>CFBundleVersion</key><string>${buildNumber}</string>
  <key>NSExtension</key>
  <dict>
    <key>NSExtensionPointIdentifier</key><string>com.apple.widgetkit-extension</string>
  </dict>
</dict>
</plist>
`;
}

function withLiveActivitiesInfoPlist(config) {
  return withInfoPlist(config, (cfg) => {
    cfg.modResults.NSSupportsLiveActivities = true;
    return cfg;
  });
}

function withWidgetFiles(config) {
  return withDangerousMod(config, [
    'ios',
    (cfg) => {
      const iosRoot = cfg.modRequest.platformProjectRoot;
      const widgetDir = path.join(iosRoot, TARGET);
      fs.mkdirSync(widgetDir, { recursive: true });
      for (const file of WIDGET_SOURCES) {
        const source =
          file === 'GhostexVoiceActivityAttributes.swift' ? ATTRIBUTES_SOURCE : path.join(TEMPLATE_DIR, file);
        fs.copyFileSync(source, path.join(widgetDir, file));
      }
      const version = cfg.version ?? '1.0.0';
      const buildNumber = cfg.ios?.buildNumber ?? '1';
      fs.writeFileSync(path.join(widgetDir, 'Info.plist'), widgetInfoPlist(version, buildNumber));
      const appDir = path.join(iosRoot, cfg.modRequest.projectName);
      fs.copyFileSync(path.join(TEMPLATE_DIR, 'GhostexVoiceTalkIntent.swift'), path.join(appDir, APP_INTENT_FILE));
      return cfg;
    },
  ]);
}

function withWidgetTarget(config) {
  return withXcodeProject(config, (cfg) => {
    addWidgetTarget(cfg.modResults, {
      appName: cfg.modRequest.projectName,
      bundleIdentifier: cfg.ios?.bundleIdentifier ?? 'com.maddada.ghostex.ios',
      appleTeamId: cfg.ios?.appleTeamId,
    });
    return cfg;
  });
}

/**
 * Adds the extension target to an `xcode` project: its group, sources, build settings and embedding
 * in the app, and the app's copy of the intent. Does nothing when the target is already there.
 */
function addWidgetTarget(project, { appName, bundleIdentifier, appleTeamId }) {
  if (findWidgetTarget(project)) return false;

  const appTarget = project.getFirstTarget();
  const appSettings = appBuildSettings(project, appTarget.firstTarget);
  // `addTarget` makes the app depend on the extension only where these sections already exist;
  // Expo's template has none, which would leave the app building it only by Xcode's guesswork.
  const objects = project.hash.project.objects;
  objects.PBXTargetDependency ??= {};
  objects.PBXContainerItemProxy ??= {};
  const target = project.addTarget(TARGET, 'app_extension', TARGET, `${bundleIdentifier}.VoiceActivity`);

  // `addTarget` names the product without its extension; the embed step copies it by this path.
  const productRef = project.pbxFileReferenceSection()[target.pbxNativeTarget.productReference];
  productRef.path = `"${TARGET}.appex"`;
  productRef.name = `"${TARGET}.appex"`;

  // The extension's folder in the project navigator, holding its sources and Info.plist.
  const group = project.addPbxGroup([...WIDGET_SOURCES, 'Info.plist'], TARGET, TARGET);
  project.addToPbxGroup(group.uuid, project.getFirstProject().firstProject.mainGroup);

  project.addBuildPhase(WIDGET_SOURCES, 'PBXSourcesBuildPhase', 'Sources', target.uuid);
  project.addBuildPhase([], 'PBXResourcesBuildPhase', 'Resources', target.uuid);
  project.addBuildPhase([], 'PBXFrameworksBuildPhase', 'Frameworks', target.uuid);

  const configurations = project.pbxXCBuildConfigurationSection();
  const list = project.pbxXCConfigurationList()[target.pbxNativeTarget.buildConfigurationList];
  for (const ref of list.buildConfigurations) {
    const settings = configurations[ref.value].buildSettings;
    const debug = configurations[ref.value].name === 'Debug';
    Object.assign(settings, {
      APPLICATION_EXTENSION_API_ONLY: 'YES',
      CLANG_ENABLE_MODULES: 'YES',
      CODE_SIGN_STYLE: 'Automatic',
      DEVELOPMENT_TEAM: appleTeamId ?? appSettings.DEVELOPMENT_TEAM ?? '""',
      GENERATE_INFOPLIST_FILE: 'NO',
      INFOPLIST_FILE: `${TARGET}/Info.plist`,
      IPHONEOS_DEPLOYMENT_TARGET: appSettings.IPHONEOS_DEPLOYMENT_TARGET ?? '16.4',
      LD_RUNPATH_SEARCH_PATHS: '"$(inherited) @executable_path/Frameworks @executable_path/../../Frameworks"',
      SDKROOT: 'iphoneos',
      SKIP_INSTALL: 'YES',
      SWIFT_OPTIMIZATION_LEVEL: debug ? '"-Onone"' : '"-O"',
      SWIFT_VERSION: '5.0',
      TARGETED_DEVICE_FAMILY: '"1,2"',
    });
  }

  // The app's own copy of the Talk / Send intent (see GhostexVoiceTalkIntent.swift).
  IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
    filepath: `${appName}/${APP_INTENT_FILE}`,
    groupName: appName,
    project,
    targetUuid: appTarget.uuid,
  });
  dropUndefinedFields(project, new Set([...WIDGET_SOURCES, 'Info.plist', APP_INTENT_FILE, `${TARGET}.appex`]));
  return true;
}

/**
 * The `xcode` package writes fields it has no value for as the word `undefined`
 * (`explicitFileType = undefined;`); they are left out of this plugin's file references instead.
 */
function dropUndefinedFields(project, names) {
  const references = project.pbxFileReferenceSection();
  for (const [key, reference] of Object.entries(references)) {
    if (key.endsWith('_comment') || typeof reference !== 'object') continue;
    if (!names.has(String(reference.name ?? reference.path).replace(/"/g, ''))) continue;
    for (const field of Object.keys(reference)) {
      if (reference[field] === undefined || reference[field] === 'undefined') delete reference[field];
    }
  }
}

/** The extension's PBXNativeTarget, or null. `addTarget` stores the name quoted, so both forms count. */
function findWidgetTarget(project) {
  const targets = project.pbxNativeTargetSection();
  for (const [key, target] of Object.entries(targets)) {
    if (key.endsWith('_comment') || typeof target !== 'object') continue;
    if (target.name === TARGET || target.name === `"${TARGET}"`) return target;
  }
  return null;
}

/** The app target's Debug build settings (deployment target, team). */
function appBuildSettings(project, nativeTarget) {
  const configurations = project.pbxXCBuildConfigurationSection();
  const list = project.pbxXCConfigurationList()[nativeTarget.buildConfigurationList];
  const debug =
    list.buildConfigurations.find((ref) => configurations[ref.value].name === 'Debug') ?? list.buildConfigurations[0];
  return configurations[debug.value].buildSettings;
}

function withVoiceLiveActivity(config) {
  config = withLiveActivitiesInfoPlist(config);
  config = withWidgetFiles(config);
  config = withWidgetTarget(config);
  return config;
}

module.exports = withVoiceLiveActivity;
module.exports.addWidgetTarget = addWidgetTarget;
module.exports.findWidgetTarget = findWidgetTarget;
module.exports.widgetInfoPlist = widgetInfoPlist;
module.exports.TARGET = TARGET;
