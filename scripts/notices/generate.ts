/// <reference types="node" />
/**
 * Writes THIRD_PARTY_NOTICES.md: one entry with the full licence text for each third-party component the
 * collectors find in what the iOS app ships: the npm packages in the JavaScript bundle and those whose native code
 * is linked, the pods, React Native's prebuilt dependencies and the third-party code inside Hermes, the folders
 * under the native module's Vendor, the fonts in assets/fonts and the native module's Fonts, the generated source
 * files listed in pinned.ts, the Rust crates, standard library and compiled-in data files of the chat core, and the
 * Go modules, standard library and embedded files of the tailcat bridge. Usage (from the repo root; the README
 * lists what has to be in place first):
 *
 *   bun run notices -- --host <Ghostex main repo checkout> [--output <file>]
 *
 * The Rust chat core and the Go tailcat bridge are built from the Ghostex main repo, so their dependencies are read
 * from that checkout. The output depends only on the inputs, never on the time or the machine's file order, so a
 * rerun on an unchanged tree reproduces the committed file byte for byte; `git diff` after a rerun is the drift
 * check. Any input or licence that cannot be read stops the run with a non-zero exit and its name.
 */

import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { entryHeading, renderNotices } from '../../src/licences/notices';
import { fail, GROUPS, isDirectory, NoticesError, type Collected } from './common';
import { collectGo } from './go';
import { collectFonts, collectGeneratedData, collectVendored } from './native';
import { bundledPackageDirs, npmEntry } from './npm';
import { collectPods } from './pods';
import { collectRust } from './rust';

const REPO = fileURLToPath(new URL('../..', import.meta.url));
const GENERATOR_NOTE =
  'Generated by scripts/notices/generate.ts (`bun run notices -- --host <Ghostex main repo>`); edit the generator, not this file.';

function parseArgs(argv: readonly string[]): { host: string; output: string } {
  let host: string | undefined;
  let output = path.join(REPO, 'THIRD_PARTY_NOTICES.md');
  for (let at = 0; at < argv.length; at += 1) {
    const value = argv[at + 1];
    if (argv[at] === '--host' && value !== undefined) host = argv[++at];
    else if (argv[at] === '--output' && value !== undefined) output = path.resolve(argv[++at]);
    else fail(`Unknown argument ${argv[at]}. Usage: bun run notices -- --host <Ghostex main repo> [--output <file>]`);
  }
  if (host === undefined) fail('The Ghostex main repo checkout is missing: pass it with --host <path>.');
  const resolved = path.resolve(host);
  if (!isDirectory(resolved)) fail(`The Ghostex main repo checkout ${resolved} (--host) does not exist.`);
  return { host: resolved, output };
}

/** File order: by group, then name and version, each compared by code unit so no locale changes it. */
function compareEntries(a: Collected, b: Collected): number {
  const byGroup = GROUPS.indexOf(a.group) - GROUPS.indexOf(b.group);
  if (byGroup !== 0) return byGroup;
  const nameA = a.name.toLowerCase();
  const nameB = b.name.toLowerCase();
  if (nameA !== nameB) return nameA < nameB ? -1 : 1;
  return a.version < b.version ? -1 : a.version > b.version ? 1 : 0;
}

function collect(host: string, scratch: string): Collected[] {
  const pods = collectPods(REPO);
  const bundled = bundledPackageDirs(REPO, scratch);
  const native = [...pods.npmDirs].filter((dir) => !bundled.includes(dir)).sort();
  const all = [
    ...collectVendored(REPO),
    ...collectFonts(REPO),
    ...collectGeneratedData(REPO),
    ...bundled.map((dir) => npmEntry(REPO, dir, 'JavaScript package in the app bundle.')),
    ...native.map((dir) => npmEntry(REPO, dir, 'Package whose native iOS code the app links.')),
    ...pods.entries,
    ...collectRust(REPO, host, scratch),
    ...collectGo(REPO, host),
  ];
  // The same component can be reached twice (a package in the bundle and linked natively, a crate used by both
  // the chat core and the standard library); it is listed once, as first found.
  const unique = new Map<string, Collected>();
  for (const entry of all) if (!unique.has(entryHeading(entry))) unique.set(entryHeading(entry), entry);
  return [...unique.values()].sort(compareEntries);
}

function main(): void {
  const { host, output } = parseArgs(process.argv.slice(2));
  const scratch = mkdtempSync(path.join(tmpdir(), 'ghostex-notices-'));
  try {
    const entries = collect(host, scratch);
    writeFileSync(output, renderNotices(entries, GENERATOR_NOTE));
    const counts = GROUPS.map((group) => `${group} ${entries.filter((entry) => entry.group === group).length}`);
    process.stdout.write(`Wrote ${path.relative(REPO, output)}: ${entries.length} entries (${counts.join(', ')}).\n`);
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

try {
  main();
} catch (error) {
  if (!(error instanceof NoticesError)) throw error;
  process.stderr.write(`notices: ${error.message}\n`);
  process.exitCode = 1;
}
