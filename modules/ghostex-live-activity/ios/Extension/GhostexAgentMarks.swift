    "amp-cli": 0xFFFFFF,
    "antigravity-cli": 0x749BFF,
    "browser": 0x82B7FF,
    "claude": 0xD97757,
    "claude-cloud": 0xD67556,
    "codebuddy": 0x72D6FF,
    "cursor-cli": 0xEDECEC,
    "codex": 0xFFFFFF,
    "copilot": 0xFFFFFF,
    "dsh": 0x4D6BFE,
    "empryo": 0x1FA31D,
    "factory-droid": 0xFF7A1A,
    "freebuff": 0xFFFFFF,
    "gemini": 0x8B9AFF,
    "grok-build": 0xFFFFFF,
    "hermes-agent": 0xF3C46B,
    "kiro": 0xA6E3FF,
    "omp": 0xC8FF62,
    "openclaude": 0xF0A68A,
    "opencode": 0x6D96C0,
    "pi": 0xC8FF62,
    "qoder": 0xA991FF,
    "rovo-dev": 0x4FC3A1,
    "zcode": 0xFFFFFF,
    "terminal": 0xFAFAFA,
  ]

  /// Lowercased agent name → icon id (`AGENT_NAME_ALIASES`).
  static let aliases: [String: String] = [
    "codex": "codex",
    "codex cli": "codex",
    "claude": "claude",
