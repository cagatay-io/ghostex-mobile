    "pi": "pi",
    "pi agent": "pi",
    "π": "pi",
    "opencode": "opencode",
    "open code": "opencode",
    "gemini": "gemini",
    "copilot": "copilot",
    "github copilot": "copilot",
    "droid": "factory-droid",
    "factory droid": "factory-droid",
    "grok": "grok-build",
    "grok build": "grok-build",
    "antigravity": "antigravity-cli",
    "antigravity cli": "antigravity-cli",
    "agy": "antigravity-cli",
    "amp": "amp-cli",
    "amp cli": "amp-cli",
    "hermes": "hermes-agent",
    "hermes agent": "hermes-agent",
    "codebuddy": "codebuddy",
